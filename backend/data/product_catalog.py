def photo(name: str) -> str:
    photo_number = int(name.removeprefix("Photo ").removesuffix(".PNG"))
    folder = next(
        folder
        for first, last, folder in PRODUCT_PHOTO_GROUPS
        if first <= photo_number <= last
    )
    if photo_number >= 62:
        extension = UPLOADED_PHOTO_EXTENSIONS.get(photo_number, "png")
        filename = f"Photo {photo_number}.{extension}"
        return f"/Images/products/{folder.replace(' ', '%20')}/{filename.replace(' ', '%20')}"
    return f"/Images/products/{folder}/photo-{photo_number:02d}.png"


